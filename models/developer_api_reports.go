package models

import (
	"strings"

	"go.mongodb.org/mongo-driver/bson/primitive"
)

// Report drafts written through the Developer API.
//
// The shape of this file is one decision, and everything else follows from it:
// a draft is NOT a report. It lives in its own collection, it is never read by
// the arrest-report, citation or incident surfaces, and nothing a key can call
// turns one into a filed record. A person with the community's own permission
// opens the draft on the website, reads it, and files it there.
//
// That is deliberate, and it is structural rather than a rule we remember to
// check. An arrest report has consequences inside a community: jail time, a
// fine, a court case. A game server cannot know whether what it observed was
// actually an arrest, and an integration that could file one would be deciding
// a thing only a person is entitled to decide. So the API's whole vocabulary
// here is "here is what I saw" — and the verb that files it does not exist on
// this surface at all.
//
// Two further separations inside the draft:
//
//   - Facts are structured and Narrative is free text, and they never share a
//     field. A reviewer has to be able to see what was observed apart from
//     what some model wrote about it.
//   - A narrative generated by a model says so, in the record, and can never
//     be labelled as evidence. See DeveloperReportNarrative.

// Draft kinds. One collection rather than three, because the review surface,
// the idempotency rule and the permission check are identical for all three
// and only the fact sheet differs.
const (
	ReportDraftKindIncident = "incident"
	ReportDraftKindArrest   = "arrest"
	ReportDraftKindCitation = "citation"
)

// Draft lifecycle.
//
// A key may only ever put a draft in ReportDraftStatusDraft. The other three
// are written by the website when a person acts on it, and a draft that has
// left the draft state is immutable to the API — a retry after a human has
// filed the report must not quietly rewrite what they filed.
const (
	ReportDraftStatusDraft     = "draft"
	ReportDraftStatusSubmitted = "submitted"
	ReportDraftStatusRejected  = "rejected"
	ReportDraftStatusWithdrawn = "withdrawn"
)

// IsValidReportDraftKind reports whether a kind is one we accept.
func IsValidReportDraftKind(kind string) bool {
	switch strings.ToLower(strings.TrimSpace(kind)) {
	case ReportDraftKindIncident, ReportDraftKindArrest, ReportDraftKindCitation:
		return true
	}
	return false
}

// ReportDraftKinds lists the kinds a key may write, for the docs and the error
// message that names them.
func ReportDraftKinds() []string {
	return []string{ReportDraftKindIncident, ReportDraftKindArrest, ReportDraftKindCitation}
}

// DeveloperReportSubject is the person a draft is about.
//
// Carried as both a resolved LPC identity and the integration's own reference.
// The resolved ids are what the website needs to attach a filed report to a
// real character; the reference is what the integration needs to reconcile.
type DeveloperReportSubject struct {
	PlayerRef   string `json:"playerRef,omitempty" bson:"playerRef,omitempty"`
	UserID      string `json:"userId,omitempty" bson:"userId,omitempty"`
	CivilianID  string `json:"civilianId,omitempty" bson:"civilianId,omitempty"`
	DisplayName string `json:"displayName,omitempty" bson:"displayName,omitempty"`
	// Synthetic says the subject is a simulated character. A reviewer seeing a
	// draft about an NPC should be told so before they file anything.
	Synthetic bool `json:"synthetic,omitempty" bson:"synthetic,omitempty"`
}

// DeveloperReportFacts is what the integration observed.
//
// Every field here is something a game server can actually know: a time, a
// place, a plate, a charge from the community's own penal code. Nothing in it
// is prose about what any of it meant.
type DeveloperReportFacts struct {
	OccurredAt string   `json:"occurredAt,omitempty" bson:"occurredAt,omitempty"`
	Location   string   `json:"location,omitempty" bson:"location,omitempty"`
	Summary    string   `json:"summary,omitempty" bson:"summary,omitempty"`
	Charges    []string `json:"charges,omitempty" bson:"charges,omitempty"`
	Vehicles   []string `json:"vehicles,omitempty" bson:"vehicles,omitempty"`
	Witnesses  []string `json:"witnesses,omitempty" bson:"witnesses,omitempty"`
	Officers   []string `json:"officers,omitempty" bson:"officers,omitempty"`
	ForceUsed  bool     `json:"forceUsed,omitempty" bson:"forceUsed,omitempty"`
	// Fields carries the template's own answers, as flat key/value strings.
	//
	// Strings rather than interface{} on purpose: a value a third party sends
	// must never arrive as a nested document, because a nested document is how
	// a value reaches a query as something other than a value. The website
	// renders these against the template's field list.
	Fields map[string]string `json:"fields,omitempty" bson:"fields,omitempty"`
}

// DeveloperReportNarrative is prose about the facts, kept apart from them.
//
// Generated carries the one claim that matters to a reviewer: whether a person
// wrote this or a model did. It is recorded in the draft rather than guessed
// at review time, and the website labels a generated narrative wherever it
// appears.
//
// There is deliberately no evidence field here, and no way to mark a narrative
// as one. A narrative is an account of events; evidence is a thing that
// exists. Conflating them in a system that produces jail time would be a
// mistake we could not take back, so the shape refuses it.
type DeveloperReportNarrative struct {
	Text string `json:"text,omitempty" bson:"text,omitempty"`
	// Generated is true when a model wrote the text. An integration that does
	// not say either way is treated as generated, because that is the safer
	// default for a surface whose callers are automated by definition.
	Generated   bool   `json:"generated" bson:"generated"`
	GeneratedBy string `json:"generatedBy,omitempty" bson:"generatedBy,omitempty"`
}

// DeveloperReportAttachment is metadata about something stored elsewhere.
//
// Metadata and a link only. We host no bytes for this surface, which is why
// there is no upload endpoint: accepting third-party binaries would mean
// scanning, quotas and a takedown path, and none of that is needed to let a
// reviewer click through to a clip the server already recorded.
//
// Kind is never "evidence". See ReportAttachmentKinds.
type DeveloperReportAttachment struct {
	ID          string             `json:"id" bson:"id"`
	Kind        string             `json:"kind" bson:"kind"`
	Label       string             `json:"label,omitempty" bson:"label,omitempty"`
	URL         string             `json:"url" bson:"url"`
	ContentType string             `json:"contentType,omitempty" bson:"contentType,omitempty"`
	SizeBytes   int64              `json:"sizeBytes,omitempty" bson:"sizeBytes,omitempty"`
	AddedByKey  string             `json:"addedByKeyId,omitempty" bson:"addedByKeyId,omitempty"`
	AddedAt     primitive.DateTime `json:"addedAt" bson:"addedAt"`
}

// DeveloperReportDraft is one reviewable draft.
//
// Idempotent on (CommunityID, SourceName, ExternalID). That triple is the
// unique index, and it is the same rule the dispatch surface uses, for the same
// reason: a game server retries, and a retry must not put a second draft in a
// reviewer's queue.
type DeveloperReportDraft struct {
	ID          primitive.ObjectID `json:"id" bson:"_id"`
	CommunityID string             `json:"communityId" bson:"communityId"`
	Kind        string             `json:"kind" bson:"kind"`
	Status      string             `json:"status" bson:"status"`

	SourceName string `json:"source" bson:"sourceName"`
	ExternalID string `json:"externalId" bson:"externalId"`

	// CallID is ours and CallExternalID is the integration's. Both are kept so
	// a reviewer can open the call and the integration can reconcile without
	// having stored our id.
	CallID         string `json:"callId,omitempty" bson:"callId,omitempty"`
	CallExternalID string `json:"callExternalId,omitempty" bson:"callExternalId,omitempty"`

	// TemplateSlug names the community's own form this draft answers, when the
	// integration chose one. Validated against the community's templates and
	// the reporting officer's access to it, so a key cannot propose a draft
	// against a form the officer may not use.
	TemplateSlug string `json:"templateSlug,omitempty" bson:"templateSlug,omitempty"`
	DepartmentID string `json:"departmentId,omitempty" bson:"departmentId,omitempty"`

	Subject     DeveloperReportSubject      `json:"subject" bson:"subject"`
	Facts       DeveloperReportFacts        `json:"facts" bson:"facts"`
	Narrative   DeveloperReportNarrative    `json:"narrative" bson:"narrative"`
	Charges     []ArrestCharge              `json:"charges,omitempty" bson:"charges,omitempty"`
	Attachments []DeveloperReportAttachment `json:"attachments,omitempty" bson:"attachments,omitempty"`

	// ReportingOfficer is the player the integration says observed this, and
	// the person whose community permission was checked before the draft was
	// accepted. A draft nobody can be named for is refused.
	ReportingOfficerID   string `json:"reportingOfficerId" bson:"reportingOfficerId"`
	ReportingOfficerName string `json:"reportingOfficerName,omitempty" bson:"reportingOfficerName,omitempty"`

	// Review is filled in by the website, never by the API.
	ReviewedBy      string              `json:"reviewedBy,omitempty" bson:"reviewedBy,omitempty"`
	ReviewedByName  string              `json:"reviewedByName,omitempty" bson:"reviewedByName,omitempty"`
	ReviewedAt      *primitive.DateTime `json:"reviewedAt,omitempty" bson:"reviewedAt,omitempty"`
	ReviewNotes     string              `json:"reviewNotes,omitempty" bson:"reviewNotes,omitempty"`
	FiledRecordID   string              `json:"filedRecordId,omitempty" bson:"filedRecordId,omitempty"`
	FiledRecordKind string              `json:"filedRecordKind,omitempty" bson:"filedRecordKind,omitempty"`

	Source    *RecordSource      `json:"source_,omitempty" bson:"source,omitempty"`
	CreatedAt primitive.DateTime `json:"createdAt" bson:"createdAt"`
	UpdatedAt primitive.DateTime `json:"updatedAt" bson:"updatedAt"`
}

// IsOpenForWrites reports whether a key may still change this draft.
//
// Only while it is a draft. Once a person has filed or rejected it, a late
// retry from the integration must leave their decision alone.
func (d DeveloperReportDraft) IsOpenForWrites() bool {
	return d.Status == "" || d.Status == ReportDraftStatusDraft
}

// Attachment kinds a draft may carry.
//
// "evidence" is absent and will stay absent. A link an integration supplies is
// a pointer to something we have not seen, held by a server we do not control;
// calling it evidence in a system that produces jail time would give it a
// standing it has not earned. A reviewer can look at a clip and decide for
// themselves what it is.
const (
	ReportAttachmentKindClip       = "clip"
	ReportAttachmentKindScreenshot = "screenshot"
	ReportAttachmentKindLog        = "log"
	ReportAttachmentKindDocument   = "document"
	ReportAttachmentKindOther      = "other"
)

// ReportAttachmentKinds lists the kinds an attachment may declare.
func ReportAttachmentKinds() []string {
	return []string{
		ReportAttachmentKindClip,
		ReportAttachmentKindScreenshot,
		ReportAttachmentKindLog,
		ReportAttachmentKindDocument,
		ReportAttachmentKindOther,
	}
}

// IsValidReportAttachmentKind reports whether a kind is one we accept.
func IsValidReportAttachmentKind(kind string) bool {
	for _, k := range ReportAttachmentKinds() {
		if k == strings.ToLower(strings.TrimSpace(kind)) {
			return true
		}
	}
	return false
}
